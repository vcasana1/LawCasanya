# Dirichlet-character energy identity for m=4,5,8 using explicit character tables on the unit groups.
def character_table(mod):
    units=[r for r in range(mod) if gcd(r,mod)==1]
    if mod==4:
        chars=[{1:1,3:1},{1:1,3:-1}]
    elif mod==5:
        # unit group generated by 2; four characters exp(2*pi*i*k*ell/4)
        powers=[1,2,4,3]
        chars=[]
        for k in range(4):
            chars.append({r:np.exp(2j*np.pi*k*l/4) for l,r in enumerate(powers)})
    elif mod==8:
        # C2 x C2, represent r=(-1)^a 3^b mod 8
        coords={1:(0,0),7:(1,0),3:(0,1),5:(1,1)}
        chars=[]
        for u in [0,1]:
            for v in [0,1]:
                chars.append({r:(-1)**(u*a+v*b) for r,(a,b) in coords.items()})
    else: raise ValueError(mod)
    return units,chars
