"""Version 11 audits: level returns, negative excursions, and prime/ordinal energy.

All arrays are those generated by build_data.py for 1 <= n <= 10^6.
The script verifies exact identities first and reports finite-range diagnostics
separately; no numerical output is used as a proof.
"""
from collections import defaultdict
from pathlib import Path
import math
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"

mu = np.load(DATA / "mu.npy")
M = np.load(DATA / "M.npy")
Q = np.load(DATA / "Q.npy")
S = np.load(DATA / "S.npy")
SS = np.load(DATA / "SS.npy")
pr = np.load(DATA / "pr.npy")
N = len(mu)


def occupancy(x):
    _, counts = np.unique(x, return_counts=True)
    prob = counts / counts.sum()
    e2 = float(np.dot(prob, prob))
    return {
        "support": len(counts),
        "max_mult": int(counts.max()),
        "H1_bits": float(-np.dot(prob, np.log2(prob))),
        "E2": e2,
        "H2_bits": -math.log2(e2),
        "pairs": int(np.sum(counts * (counts - 1) // 2)),
    }


# Exact non-prime controls.
Np = np.cumsum(mu == 1, dtype=np.int64)
Nm = np.cumsum(mu == -1, dtype=np.int64)
N0 = np.arange(1, N + 1, dtype=np.int64) - Q

S_pos = mu.astype(np.int64)
S_pos[mu == 0] = 1
SS_pos = np.cumsum(S_pos, dtype=np.int64)

S_ord = np.ones(N, dtype=np.int64)
S_ord[mu == 1] = Np[mu == 1]
S_ord[mu == -1] = -Nm[mu == -1]
SS_ord = np.cumsum(S_ord, dtype=np.int64)

SS_pos_formula = N0 + M
SS_ord_formula = N0 + M * (Q + 1) // 2
assert np.array_equal(SS_pos, SS_pos_formula)
assert np.array_equal(SS_ord, SS_ord_formula)

u = (Q + M) // 2
v = (Q - M) // 2
D = np.cumsum(pr - np.arange(len(pr), dtype=np.int64), dtype=np.int64)
prime_excess = D[u] - D[v]
assert np.array_equal(SS - SS_ord, prime_excess)

print("=== Exact prime/ordinal identities ===")
print("max |SS_pos-(n-Q+M)|                 :", int(np.max(np.abs(SS_pos - SS_pos_formula))))
print("max |SS_ord-(n-Q+M(Q+1)/2)|         :", int(np.max(np.abs(SS_ord - SS_ord_formula))))
print("max |SS-SS_ord-(D(N+)-D(N-))|       :", int(np.max(np.abs(SS - SS_ord - prime_excess))))

T_prime = SS - N0
T_ord = SS_ord - N0
if M[-1] != 0:
    print("endpoint N                             :", N)
    print("endpoint (Q,M,n-Q)                    :", int(Q[-1]), int(M[-1]), int(N0[-1]))
    print("endpoint T_ord, T_prime               :", int(T_ord[-1]), int(T_prime[-1]))
    print("endpoint amplitude ratio              : %.12f" % (T_prime[-1] / T_ord[-1]))
    print("endpoint squared-energy ratio         : %.12f" % ((T_prime[-1] / T_ord[-1]) ** 2))


# Squarefree clock, including q=0.
sf_n = np.flatnonzero(mu) + 1
eps = mu[sf_n - 1].astype(np.int64)
R = np.r_[0, np.cumsum(eps, dtype=np.int64)]
sf_phys = np.r_[0, sf_n]
SS_sf = np.r_[0, SS[sf_n - 1]]

# Crossing identity at every squarefree occurrence.
q = np.arange(1, len(R), dtype=np.int64)
h = R[1:]
pred = np.empty_like(h)
up = eps == 1
pred[up] = pr[(q[up] + h[up]) // 2]
pred[~up] = -pr[(q[~up] - h[~up]) // 2]
assert np.array_equal(pred, S[sf_n - 1])
zero_reached = h == 0
assert np.all(np.abs(pred[zero_reached]) == pr[q[zero_reached] // 2])
assert np.all(SS_sf[1:][zero_reached] == sf_phys[1:][zero_reached] - q[zero_reached])

print("\n=== Level-crossing audit ===")
print("squarefree crossings tested           :", len(q))
print("max increment-formula error           :", int(np.max(np.abs(pred - S[sf_n - 1]))))
print("returns reaching level zero           :", int(np.sum(zero_reached)))


# Same-level collision pairs on the squarefree clock.
by_level = defaultdict(list)
for rr, val in zip(R[1:], SS_sf[1:]):
    by_level[int(rr)].append(int(val))
collision_levels = {}
for lev, values in by_level.items():
    _, counts = np.unique(values, return_counts=True)
    pairs = int(np.sum(counts * (counts - 1) // 2))
    if pairs:
        collision_levels[lev] = pairs

print("\n=== Same-level SS collisions, squarefree clock ===")
print("levels with collisions                :", sorted(collision_levels.items()))


# Complete negative excursions between consecutive visits to R=0.
zero_q = np.flatnonzero(R == 0)
excursions = []
for left, right in zip(zero_q[:-1], zero_q[1:]):
    interior = R[left + 1:right]
    if len(interior) == 0 or not np.all(interior < 0):
        continue
    H = int(-interior.min())
    total = 0
    min_bound = (H ** 3 - H) // 3
    identity_error = 0
    for k in range(1, H):
        visits = np.flatnonzero(R[left:right + 1] == -k) + left
        first, last = int(visits[0]), int(visits[-1])
        r = (last - first) // 2
        Z = int(sf_phys[last] - sf_phys[first] - (last - first))
        Ak = int(Z - (SS_sf[last] - SS_sf[first]))
        Aplus = (first - k) // 2
        prime_sep = sum(int(pr[Aplus + k + t] - pr[Aplus + t]) for t in range(1, r + 1))
        identity_error = max(identity_error, abs(Ak - prime_sep))
        assert r >= H - k
        assert Ak >= 2 * k * r
        total += Ak
    assert total >= min_bound
    excursions.append((H, total, min_bound, identity_error, int(sf_phys[left]), int(sf_phys[right])))

excursions.sort(reverse=True)
print("\n=== Complete negative excursions ===")
print("number of complete negative excursions:", len(excursions))
print("nontrivial excursions with H >= 2       :", sum(x[0] >= 2 for x in excursions))
print("max exact-identity error               :", max(x[3] for x in excursions))
print("largest excursions: H, A, cubic bound, ratio, physical endpoints")
for H, total, bound, err, left, right in excursions[:10]:
    ratio = total / bound if bound else float("nan")
    print("%4d %14d %12d %12.6f %9d %9d" % (H, total, bound, ratio, left, right))


print("\n=== Finite occupancy diagnostics (not proofs) ===")
for name, x in [("M", M), ("SS_pos", SS_pos), ("SS_ord", SS_ord), ("SS_prime", SS)]:
    z = occupancy(x)
    print(
        "%-9s support=%7d maxmult=%5d H1=%12.9f E2=%.12e H2=%12.9f pairs=%d"
        % (name, z["support"], z["max_mult"], z["H1_bits"], z["E2"], z["H2_bits"], z["pairs"])
    )
